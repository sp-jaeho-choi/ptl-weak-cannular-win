// 사이트별 약물 라벨 팩 (예시)
//
// 워크스테이션은 설치 폴더 plugins\ 안의 .js 를 시작할 때 전부 불러온다.
// 병원마다 쓰는 약물 표기와 알람 문구가 달라, 본체를 다시 배포하지 않고
// 이 경로에 파일만 떨어뜨려 바꿀 수 있게 해 두었다.
//
// ⚠ 로드 시 서명·출처를 확인하지 않는다. 이 폴더에 쓸 수 있는 사람은
//    워크스테이션 프로세스에서 임의 코드를 실행할 수 있다.

exports.name = 'site-drug-labels'
exports.version = '1.1.0'

exports.init = function (ctx) {
  ctx.registerDrugLabels({
    1: '모르핀 (1 mg/mL)',
    2: '펜타닐 (50 mcg/mL)',
    3: '인슐린 (1 U/mL)',
    4: '헤파린 (1000 U/mL)',
    5: '도파민 (400 mg/250 mL)',
    6: '시험용 (교정 전용)'
  })

  ctx.registerAlarmLabels({
    1: '폐색 — 라인/필터 확인',
    2: '공기 감지 — 라인 프라이밍 필요',
    3: '배터리 부족 — 전원 연결',
    4: '주입 완료 / 저장통 비었음',
    5: '용량 상한 초과 — 처방 확인',
    9: '유량 오류 — 세트 재장착'
  })

  ctx.log('약물/알람 라벨 팩 적용 (ICU-3)')
}
